/* ---------- tiny in-memory rate limiter (per instance; add Upstash/Redis for multi-region) ---------- */
const buckets = new Map();
function limited(key, max, windowMs) {
  const now = Date.now(), b = buckets.get(key) || []; const recent = b.filter(t => now - t < windowMs);
  if (recent.length >= max) { buckets.set(key, recent); return true }
  recent.push(now); buckets.set(key, recent); if (buckets.size > 5000) buckets.clear(); return false;
}
const json = (status, body) => ({ status, body });

/* ================= CHAT ================= */
async function embedQueryNeural(q) {
  const r = await fetch((env('OPENAI_BASE_URL') || 'https://api.openai.com/v1') + '/embeddings', { method: 'POST', headers: { 'content-type': 'application/json', authorization: 'Bearer ' + env('OPENAI_API_KEY') }, body: JSON.stringify({ model: index().neural.model, input: q }) });
  if (!r.ok) throw new Error('embed ' + r.status); return (await r.json()).data[0].embedding;
}
async function callLLM(messages) {
  if (env('ANTHROPIC_API_KEY')) {
    const r = await fetch('https://api.anthropic.com/v1/messages', { method: 'POST', headers: { 'content-type': 'application/json', 'x-api-key': env('ANTHROPIC_API_KEY'), 'anthropic-version': '2023-06-01' },
      body: JSON.stringify({ model: env('CHAT_MODEL') || 'claude-haiku-5-5', max_tokens: 400, temperature: 0.2, system: P.SYSTEM, messages }) });
    if (!r.ok) throw new Error('anthropic ' + r.status + ' ' + (await r.text()).slice(0, 200));
    const j = await r.json(); return { text: j.content.map(c => c.text || '').join('').trim(), provider: 'anthropic:' + j.model };
  }
  if (env('OPENAI_API_KEY') || env('LLM_API_KEY')) {     // OpenAI or any OpenAI-compatible API (Groq, OpenRouter, Together…)
    const r = await fetch((env('LLM_BASE_URL') || env('OPENAI_BASE_URL') || 'https://api.openai.com/v1') + '/chat/completions', { method: 'POST', headers: { 'content-type': 'application/json', authorization: 'Bearer ' + (env('LLM_API_KEY') || env('OPENAI_API_KEY')) },
      body: JSON.stringify({ model: env('CHAT_MODEL') || 'gpt-4o-mini', temperature: 0.2, max_tokens: 400, messages: [{ role: 'system', content: P.SYSTEM }, ...messages] }) });
    if (!r.ok) throw new Error('llm ' + r.status + ' ' + (await r.text()).slice(0, 200));
    const j = await r.json(); return { text: j.choices[0].message.content.trim(), provider: 'openai-compatible:' + j.model };
  }
  return null;
}
export async function handleChat(body, ctx = {}) {
  if (limited('chat:' + (ctx.ip || '?'), 20, 60_000)) return json(429, { error: 'Too many questions — please wait a minute.' });
  const q = Rules.clean(body && body.question).slice(0, 500);
  if (q.length < 2) return json(400, { error: 'Please type a question.' });
  const history = Array.isArray(body.history) ? body.history.slice(-6).filter(m => m && (m.role === 'user' || m.role === 'assistant')).map(m => ({ role: m.role, content: Rules.clean(m.content).slice(0, 800) })) : [];
  const idx = index();
  const lastUser = [...history].reverse().find(m => m.role === 'user');
  let neural = null;
  if (idx.neural && env('OPENAI_API_KEY')) {
    try { const qv = await embedQueryNeural(q); neural = idx.neural.vectors.map(v => { let s = 0; for (let i = 0; i < v.length; i++) s += v[i] * qv[i]; return s }) } catch (e) { console.warn(e.message) }
  }
  const hits = RAG.retrieve(idx, q, lastUser && lastUser.content, 4, neural);
  const sources = hits.map((h, i) => ({ n: i + 1, title: h.title, heading: h.heading, section: h.section, score: h.score }));
  if (!RAG.answerable(hits)) return json(200, { answer: P.NOT_FOUND, sources: [], grounded: false, mode: 'retrieval' });
  const messages = [...history.slice(-4), { role: 'user', content: P.userMessage(q, hits) }];
  try {
    const out = await callLLM(messages);
    if (out) return json(200, { answer: out.text, sources, grounded: !out.text.startsWith("I don't have"), mode: 'llm', provider: out.provider });
  } catch (e) { console.error('LLM error:', e.message) }
  return json(200, { answer: P.extractive(q, hits, RAG), sources, grounded: true, mode: 'extractive' });
}

