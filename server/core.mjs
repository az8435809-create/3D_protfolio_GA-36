const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
async function verifyTurnstile(token, ip) {
  if (!env('TURNSTILE_SECRET')) return true;
  const r = await fetch('https://challenges.cloudflare.com/turnstile/v0/siteverify', { method: 'POST', body: new URLSearchParams({ secret: env('TURNSTILE_SECRET'), response: token || '', remoteip: ip || '' }) });
  return (await r.json()).success === true;
}
export async function handleContact(body, ctx = {}) {
  body = body || {};
  // 1) spam traps: hidden honeypot field + too-fast submissions (bots fill forms instantly)
  if (Rules.clean(body.website)) return json(200, { ok: true, id: 'filtered' });          // pretend success to the bot
  const elapsed = Date.now() - Number(body.startedAt || 0);
  if (!body.startedAt || elapsed < 3000 || elapsed > 86_400_000) return json(400, { ok: false, error: 'Please take a moment to fill in the form, then send it again.' });
  // 2) rate limit per IP: 3 messages / 10 min, 10 / day
  const ip = ctx.ip || '?';
  if (limited('c10:' + ip, 3, 600_000) || limited('cday:' + ip, 10, 86_400_000)) return json(429, { ok: false, error: 'Too many messages from your network. Please try again later or email directly.' });
  // 3) validation (same rules as the browser)
  const { values: v, errors, ok } = Rules.validate(body);
  if (!ok) return json(422, { ok: false, error: 'Please fix the highlighted fields.', errors });
  if (Rules.spamScore(v) >= 3) return json(422, { ok: false, error: 'Your message looks like spam. Please remove links or promotional text.' });
  if (!(await verifyTurnstile(body.turnstileToken, ip))) return json(400, { ok: false, error: 'Spam check failed. Please refresh and try again.' });
  // 4) compose (all user input escaped for HTML; headers are single-line)
  const to = env('CONTACT_TO'); const from = env('CONTACT_FROM') || env('SMTP_USER');
  if (!to || !from) return json(500, { ok: false, error: 'The message service is not configured yet. Please email az8435809@gmail.com directly.' });
  const subject = `Portfolio message: ${v.subject}`;
  const text = `New message from your portfolio contact form\n\nName: ${v.name}\nEmail: ${v.email}\nSubject: ${v.subject}\n\n${v.message}\n\n— Sent ${new Date().toISOString()} · IP ${ip}`;
  const html = `<div style="font-family:Arial,sans-serif;max-width:600px;margin:auto;border:1px solid #e5dcc4;border-radius:12px;overflow:hidden">
<div style="background:#12211A;color:#F5F0E6;padding:18px 22px"><b style="font-size:18px">New portfolio message</b><br><span style="color:#E8B923;font-size:13px">via alizain portfolio contact form</span></div>
<div style="padding:22px;color:#222"><p><b>Name:</b> ${esc(v.name)}<br><b>Email:</b> <a href="mailto:${esc(v.email)}">${esc(v.email)}</a><br><b>Subject:</b> ${esc(v.subject)}</p>
<div style="white-space:pre-wrap;background:#faf7ef;border-left:4px solid #D9A821;padding:14px 16px;border-radius:6px">${esc(v.message)}</div>
<p style="color:#888;font-size:12px">Reply directly to this email to answer ${esc(v.name)}. Sent ${new Date().toUTCString()}.</p></div></div>`;
  const replyTo = `"${v.name.replace(/["\\]/g, '')}" <${v.email}>`;
  try {
    let res;
    if (env('RESEND_API_KEY')) {
      const r = await fetch(env('RESEND_API_URL') || 'https://api.resend.com/emails', { method: 'POST', headers: { 'content-type': 'application/json', authorization: 'Bearer ' + env('RESEND_API_KEY') },
        body: JSON.stringify({ from, to: [to], reply_to: v.email, subject, text, html }) });
      if (!r.ok) throw new Error('resend ' + r.status + ' ' + (await r.text()).slice(0, 200));
      res = { id: (await r.json()).id, provider: 'resend' };
    } else if (env('SMTP_HOST')) {
      res = await sendSMTP({ host: env('SMTP_HOST'), port: +(env('SMTP_PORT') || 465), secure: env('SMTP_SECURE') ? env('SMTP_SECURE') === 'true' : +(env('SMTP_PORT') || 465) === 465,
        user: env('SMTP_USER'), pass: env('SMTP_PASS'), from, to, replyTo, subject, text, html });
    } else return json(500, { ok: false, error: 'The message service is not configured yet. Please email az8435809@gmail.com directly.' });
    console.log('contact: delivered', res.provider, res.id);
    return json(200, { ok: true, id: res.id });
  } catch (e) {
    console.error('contact: send failed', e.message);
    return json(502, { ok: false, error: 'Your message could not be sent right now. Please try again, or email az8435809@gmail.com directly.' });
  }
}
